#ifndef LLVM_LIB_TARGET_ALPHA_ALPHASUBTARGET_H
#define LLVM_LIB_TARGET_ALPHA_ALPHASUBTARGET_H

#include "AlphaFrameLowering.h"
#include "AlphaISelLowering.h"
#include "AlphaInstrInfo.h"
#include "MCTargetDesc/AlphaMCTargetDesc.h"
#include "llvm/ADT/BitVector.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>

#define GET_SUBTARGETINFO_HEADER
#include "AlphaGenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class AlphaSubtarget : public AlphaGenSubtargetInfo {
  // Integer registers reserved from allocation via -ffixed-$<n>.  Indexed by
  // physical register number; must be constructed before the feature string is
  // parsed, so it is declared ahead of the generated members below.
  BitVector ReserveRegister;

  // Bool members corresponding to the SubtargetFeatures defined in tablegen.
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "AlphaGenSubtargetInfo.inc"

  AlphaInstrInfo InstrInfo;
  AlphaTargetLowering TLInfo;
  AlphaFrameLowering FrameLowering;
  AlphaSelectionDAGInfo TSInfo;

  AlphaSubtarget &initializeSubtargetDependencies(StringRef CPU,
                                                  StringRef TuneCPU,
                                                  StringRef FS);

public:
  // TuneCPU selects the scheduling model and the tuning-only decisions; CPU
  // alone decides which instructions may be emitted. An empty TuneCPU tunes
  // for CPU.
  AlphaSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                 StringRef FS, const TargetMachine &TM);

  const AlphaInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const AlphaRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const AlphaTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const AlphaFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  bool hasBWX() const { return HasBWX; }
  bool hasIEEE() const { return HasIEEE; }
  bool hasMVI() const { return HasMVI; }
  bool hasFIX() const { return HasFIX; }
  bool hasCIX() const { return HasCIX; }
  bool hasPrefetch() const { return HasPrefetch; }
  bool hasSafeBWA() const { return HasSafeBWA; }
  bool hasSafePartial() const { return HasSafePartial; }
  bool hasSmallData() const { return HasSmallData; }
  bool hasSmallText() const { return HasSmallText; }
  bool hasBuildConstants() const { return HasBuildConstants; }
  bool hasNoFPRegs() const { return HasNoFPRegs; }
  bool hasTrapPrecisionInsn() const { return HasTrapPrecisionInsn; }
  bool hasIEEEConformant() const { return HasIEEEConformant; }
  bool hasPreciseArithTraps() const { return HasPreciseArithTraps; }

  // Whether physical register PhysReg was reserved with -ffixed-$<n>.
  bool isRegisterReserved(MCPhysReg PhysReg) const {
    return ReserveRegister[PhysReg];
  }

  // Automatically generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_ALPHA_ALPHASUBTARGET_H
