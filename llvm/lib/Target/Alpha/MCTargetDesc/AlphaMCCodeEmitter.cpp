#include "AlphaFixupKinds.h"
#include "AlphaMCTargetDesc.h"
#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/Support/Casting.h"
#include "llvm/Support/EndianStream.h"
#include "llvm/Support/MathExtras.h"

using namespace llvm;

namespace {
class AlphaMCCodeEmitter : public MCCodeEmitter {
  AlphaMCCodeEmitter(const AlphaMCCodeEmitter &) = delete;
  void operator=(const AlphaMCCodeEmitter &) = delete;
  MCContext &Ctx;
  MCInstrInfo const &MCII;

public:
  AlphaMCCodeEmitter(MCContext &ctx, MCInstrInfo const &MCII)
      : Ctx(ctx), MCII(MCII) {}

  ~AlphaMCCodeEmitter() override = default;

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  // Return the encoding of an ordinary register or immediate operand.
  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  // memri: base register in bits 20-16, 16-bit displacement in bits 15-0.
  unsigned getMemEncoding(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const;

  // Symbol operands whose 16-bit displacement is provided by a relocation.
  unsigned getSymEncoding(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          Alpha::Fixups Kind) const;
  unsigned getLiteralEncoding(const MCInst &MI, unsigned OpNo,
                              SmallVectorImpl<MCFixup> &Fixups,
                              const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_literal);
  }
  unsigned getGprelHighEncoding(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_gprelhigh);
  }
  unsigned getGprelLowEncoding(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_gprellow);
  }

  // Branch target: emits a 21-bit PC-relative BRADDR fixup.
  unsigned getBranchTargetEncoding(const MCInst &MI, unsigned OpNo,
                                   SmallVectorImpl<MCFixup> &Fixups,
                                   const MCSubtargetInfo &STI) const;
};
} // end anonymous namespace

unsigned
AlphaMCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  // Bare symbol references without an explicit relocation kind are not
  // expected on ordinary operands.
  assert(MO.isExpr() && "unexpected operand kind");
  return 0;
}

unsigned AlphaMCCodeEmitter::getMemEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  unsigned Base =
      getMachineOpValue(MI, MI.getOperand(OpNo), Fixups, STI) & 0x1f;
  unsigned Disp =
      getMachineOpValue(MI, MI.getOperand(OpNo + 1), Fixups, STI) & 0xffff;
  return (Base << 16) | Disp;
}

unsigned AlphaMCCodeEmitter::getSymEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            Alpha::Fixups Kind) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm()) & 0xffff;
  assert(MO.isExpr() && "expected an expression for a relocated operand");
  Fixups.push_back(
      MCFixup::create(0, MO.getExpr(), MCFixupKind(Kind), /*PCRel=*/false));
  return 0;
}

unsigned
AlphaMCCodeEmitter::getBranchTargetEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  assert(MO.isExpr() && "expected an expression for a branch target");
  Fixups.push_back(MCFixup::create(0, MO.getExpr(),
                                   MCFixupKind(Alpha::fixup_alpha_braddr),
                                   /*PCRel=*/true));
  return 0;
}

void AlphaMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                           SmallVectorImpl<char> &CB,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  uint32_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  support::endian::write(CB, Bits, llvm::endianness::little);
}

MCCodeEmitter *llvm::createAlphaMCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  return new AlphaMCCodeEmitter(Ctx, MCII);
}

