// The branch a landing pad's gp reload is based on.  A zero displacement makes
// it fall through to the ldah it puts the address of into $29.
static constexpr uint32_t INSN_BR_GP = 0xc3a00000; // br $29, .+4

namespace {
class AlphaMCCodeEmitter : public MCCodeEmitter {
  AlphaMCCodeEmitter(const AlphaMCCodeEmitter &) = delete;
  void operator=(const AlphaMCCodeEmitter &) = delete;
  MCContext &Ctx;
  MCInstrInfo const &MCII;

public:
  AlphaMCCodeEmitter(MCContext &ctx, MCInstrInfo const &MCII)
      : Ctx(ctx), MCII(MCII) {}

  ~AlphaMCCodeEmitter() override = default;

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  // Return the encoding of an ordinary register or immediate operand.
  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  // memri: base register in bits 20-16, 16-bit displacement in bits 15-0.
  unsigned getMemEncoding(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const;

  // Symbol operands whose 16-bit displacement is provided by a relocation.
  unsigned getSymEncoding(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          Alpha::Fixups Kind) const;
  unsigned getLiteralEncoding(const MCInst &MI, unsigned OpNo,
                              SmallVectorImpl<MCFixup> &Fixups,
                              const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_literal);
  }
  unsigned getGprelHighEncoding(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_gprelhigh);
  }
  // The jsr hint field: emit an R_ALPHA_HINT relocation for the call target so
  // the linker can fill in the branch-prediction displacement.
  unsigned getHintEncoding(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    const MCOperand &MO = MI.getOperand(OpNo);
    if (MO.isExpr())
      Fixups.push_back(MCFixup::create(0, MO.getExpr(),
                                       MCFixupKind(Alpha::fixup_alpha_hint)));
    return 0;
  }
  unsigned getTlsldmEncoding(const MCInst &MI, unsigned OpNo,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_tlsldm);
  }
  unsigned getDtprelHighEncoding(const MCInst &MI, unsigned OpNo,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_dtprelhi);
  }
  unsigned getDtprelLowEncoding(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_dtprello);
  }
  unsigned getTlsgdEncoding(const MCInst &MI, unsigned OpNo,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_tlsgd);
  }
  unsigned getGotTprelEncoding(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_gottprel);
  }
  unsigned getTprelHighEncoding(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_tprelhi);
  }
  unsigned getTprelLowEncoding(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_tprello);
  }
  unsigned getGprelLowEncoding(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const {
    return getSymEncoding(MI, OpNo, Fixups, Alpha::fixup_alpha_gprellow);
  }

  // Branch target: emits a 21-bit PC-relative BRADDR fixup.
  unsigned getBranchTargetEncoding(const MCInst &MI, unsigned OpNo,
                                   SmallVectorImpl<MCFixup> &Fixups,
                                   const MCSubtargetInfo &STI) const;

  // The target of a direct call made as a branch: the same displacement, but
  // relocated BRSGP, which lets the linker aim it past the callee's gp
  // prologue.  A callee in another gp group cannot be reached this way at all;
  // bfd reports `change in gp: BRSGP' rather than interposing a stub.
  unsigned getSameGpTargetEncoding(const MCInst &MI, unsigned OpNo,
                                   SmallVectorImpl<MCFixup> &Fixups,
                                   const MCSubtargetInfo &STI) const;

  void emitLdgp(unsigned Base, SmallVectorImpl<char> &CB,
                SmallVectorImpl<MCFixup> &Fixups,
                const MCSubtargetInfo &STI) const;
};
} // end anonymous namespace

unsigned
AlphaMCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  assert(MO.isExpr() && "unexpected operand kind");
  // A relocation-specifier expression (from an assembler !literal/!gprel...
  // suffix) contributes a fixup of the requested kind.
  if (auto *SE = dyn_cast<MCSpecifierExpr>(MO.getExpr()))
    Fixups.push_back(
        MCFixup::create(0, MO.getExpr(), MCFixupKind(SE->getSpecifier())));
  return 0;
}

unsigned AlphaMCCodeEmitter::getMemEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  unsigned Base =
      getMachineOpValue(MI, MI.getOperand(OpNo), Fixups, STI) & 0x1f;
  unsigned Disp =
      getMachineOpValue(MI, MI.getOperand(OpNo + 1), Fixups, STI) & 0xffff;
  return (Base << 16) | Disp;
}

unsigned AlphaMCCodeEmitter::getSymEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            Alpha::Fixups Kind) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm()) & 0xffff;
  assert(MO.isExpr() && "expected an expression for a relocated operand");
  Fixups.push_back(
      MCFixup::create(0, MO.getExpr(), MCFixupKind(Kind), /*PCRel=*/false));
  return 0;
}

// Shared by the two branch-target operand kinds; Default is the relocation to
// use when the operand carries no explicit relocation specifier of its own.
static unsigned encodeBranchTarget(const MCOperand &MO, MCContext &Ctx,
                                   SmallVectorImpl<MCFixup> &Fixups,
                                   Alpha::Fixups Default) {
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  assert(MO.isExpr() && "expected an expression for a branch target");
  // A `!samegp` suffix requests a BRSGP relocation instead of the usual BRADDR.
  // It is the only suffix a branch displacement takes; taking whichever one was
  // written as the fixup kind put it on the branch, so `br $31, foo !literal'
  // assembled to a branch carrying R_ALPHA_LITERAL.
  Alpha::Fixups Kind = Default;
  if (auto *SE = dyn_cast<MCSpecifierExpr>(MO.getExpr())) {
    if (SE->getSpecifier() != Alpha::fixup_alpha_brsgp) {
      Ctx.reportError(MO.getExpr()->getLoc(),
                      "unsupported relocation specifier on a branch target");
      return 0;
    }
    Kind = Alpha::fixup_alpha_brsgp;
  }
  Fixups.push_back(
      MCFixup::create(0, MO.getExpr(), MCFixupKind(Kind), /*PCRel=*/true));
  return 0;
}

unsigned
AlphaMCCodeEmitter::getBranchTargetEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  return encodeBranchTarget(MI.getOperand(OpNo), Ctx, Fixups,
                            Alpha::fixup_alpha_braddr);
}

unsigned
AlphaMCCodeEmitter::getSameGpTargetEncoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  return encodeBranchTarget(MI.getOperand(OpNo), Ctx, Fixups,
                            Alpha::fixup_alpha_brsgp);
}

// Emit an ldgp expansion: ldah $29, 0(Base) with a GPDISP relocation whose
// addend is the distance to the following lda $29, 0($29).  Only the ldah
// carries the relocation.
void AlphaMCCodeEmitter::emitLdgp(unsigned Base, SmallVectorImpl<char> &CB,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const {
  // The relocation sits on the ldah, whose offset within this instruction's
  // encoding is the current buffer size (0 for ldgp, 4 for the jsr reload).
  unsigned LdahOffset = CB.size();
  MCInst Ldah;
  Ldah.setOpcode(Alpha::LDAH);
  Ldah.addOperand(MCOperand::createReg(Alpha::R29));
  Ldah.addOperand(MCOperand::createImm(0));
  Ldah.addOperand(MCOperand::createReg(Base));
  uint32_t Hi = getBinaryCodeForInstr(Ldah, Fixups, STI);
  Fixups.push_back(MCFixup::create(LdahOffset, MCConstantExpr::create(4, Ctx),
                                   MCFixupKind(Alpha::fixup_alpha_gpdisp)));
  support::endian::write(CB, Hi, llvm::endianness::little);

  MCInst Lda;
  Lda.setOpcode(Alpha::LDA);
  Lda.addOperand(MCOperand::createReg(Alpha::R29));
  Lda.addOperand(MCOperand::createImm(0));
  Lda.addOperand(MCOperand::createReg(Alpha::R29));
  uint32_t Lo = getBinaryCodeForInstr(Lda, Fixups, STI);
  support::endian::write(CB, Lo, llvm::endianness::little);
}

void AlphaMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                           SmallVectorImpl<char> &CB,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
#ifndef NDEBUG
  // The multi-instruction pseudos below declare their length in
  // AlphaInstrInfo.td and AlphaInstrInfo::getInstSizeInBytes hands it to branch
  // relaxation, which uses it to decide whether a 21-bit branch displacement
  // reaches.  A declared size smaller than what is written here makes
  // relaxation decline to relax a branch that does not actually reach, so hold
  // the two together.  The many early returns below are why this is a scope
  // guard.
  size_t StartSize = CB.size();
  llvm::scope_exit CheckSize([&] {
    unsigned Declared = MCII.get(MI.getOpcode()).getSize();
    assert((Declared == 0 || CB.size() - StartSize == Declared) &&
           "emitted byte count disagrees with the instruction's Size in "
           "AlphaInstrInfo.td");
  });
#endif
  switch (MI.getOpcode()) {
  case Alpha::LDGP:
    // ldgp $29, 0($27): establish the GP from the procedure value.
    return emitLdgp(Alpha::R27, CB, Fixups, STI);
  case Alpha::LDGPself:
    // br $29, .+4 followed by an ldgp reload from the address it just wrote:
    // establish the GP at a landing pad, which the unwinder enters with no
    // register holding anything the reload could be based on.
    support::endian::write<uint32_t>(CB, INSN_BR_GP, llvm::endianness::little);
    return emitLdgp(Alpha::R29, CB, Fixups, STI);
  case Alpha::JSR:
  case Alpha::OTS_CALL: {
    // jsr $26, ($27) followed by an ldgp reload from the return address.
    uint32_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
    support::endian::write(CB, Bits, llvm::endianness::little);
    return emitLdgp(Alpha::R26, CB, Fixups, STI);
  }
  case Alpha::JSRd:
  case Alpha::JSRdl:
  case Alpha::JSRtlsgd:
  case Alpha::JSRtlsldm: {
    // A direct jsr, or the jsr to __tls_get_addr in a dynamic TLS sequence.
    // JSRd (external callee) also fills the hint field with an R_ALPHA_HINT
    // while encoding its operand.  Every form emits an R_ALPHA_LITUSE
    // relocation marking the jsr as a use of the GOT literal so the linker can
    // relax it; the addend selects the use type: jsr (3), tlsgd (4), or tlsldm
    // (5).  JSRdl carries no hint: the linker relaxes a dso-local call into a
    // direct branch, so there is no jsr left for the hint to predict.  A hint
    // does not itself inhibit that relaxation -- GNU as writes one on exactly
    // this jsr and bfd relaxes it anyway.  The TLS forms carry none either:
    // their symbol operand is the thread-local variable rather than
    // __tls_get_addr, so there is nothing to hang one on.  The ldgp reload
    // follows as for JSR.
    size_t FirstFixup = Fixups.size();
    uint32_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
    unsigned UseType = MI.getOpcode() == Alpha::JSRtlsgd    ? 4
                       : MI.getOpcode() == Alpha::JSRtlsldm ? 5
                                                            : 3;
    // Only the addend of the lituse relocation matters -- it holds the use
    // type -- and bfd says so outright: "the symbol associated with GPDISP and
    // LITUSE is immaterial".  Emit no symbol, as the gpdisp pair does, rather
    // than naming .text, which the instruction need not be in.
    Fixups.push_back(MCFixup::create(0, MCConstantExpr::create(UseType, Ctx),
                                     MCFixupKind(Alpha::fixup_alpha_lituse_jsr)));
    // GNU as puts the lituse ahead of the hint, and bfd only inspects the
    // relocation immediately following a literal's, so match that order or the
    // GNU linker will not relax a call that has both.
    std::rotate(Fixups.begin() + FirstFixup, Fixups.end() - 1, Fixups.end());
    support::endian::write(CB, Bits, llvm::endianness::little);
    return emitLdgp(Alpha::R26, CB, Fixups, STI);
  }
  default:
    break;
  }
  uint32_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  // Set a floating-point instruction's trap-mode and rounding-mode qualifiers
  // in its function field.  An instruction that came from an assembly file or
  // from the disassembler carries its own -- whatever was written, or whatever
  // the bits said -- and that is used as is.  Only one built by codegen has
  // none, and only then do -mieee and -mfp-rounding-mode decide: applying them
  // to what someone wrote would assemble `addt' as `addt/su'.
  if (unsigned TrapClass = MCII.get(MI.getOpcode()).TSFlags & Alpha::TrapClassMask) {
    unsigned TrapBits, RM;
    if (Alpha::hasFPQual(MI.getFlags())) {
      TrapBits = Alpha::fpQualTrapBits(MI.getFlags());
      RM = Alpha::fpQualRoundMode(MI.getFlags());
    } else {
      TrapBits = Alpha::getFPTrapFuncBits(
          Alpha::getFPTrapSuffix(TrapClass, STI.hasFeature(Alpha::FeatureIEEE),
                                 STI.hasFeature(Alpha::FeatureIEEEInexact),
                                 STI.hasFeature(Alpha::FeatureFPTrapU)));
      RM = Alpha::fpRounds(TrapClass) ? getFPRoundMode(STI)
                                      : Alpha::FPRoundNormal;
    }
    Bits |= TrapBits << 5;
    if (Alpha::fpTakesWrittenRound(TrapClass) && RM != Alpha::FPRoundNormal)
      Bits = (Bits & ~(0xc0u << 5)) | (Alpha::getFPRoundFuncBits(RM) << 5);
  }
  support::endian::write(CB, Bits, llvm::endianness::little);
}

MCCodeEmitter *llvm::createAlphaMCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  return new AlphaMCCodeEmitter(Ctx, MCII);
}

